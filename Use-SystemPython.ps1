#requires -Version 5.1
<#
.SYNOPSIS
    Switch PROCURE360 to use an already-installed system Python instead of the
    bundled runtime. Useful when a corporate antivirus blocks the bundled
    python.exe from accepting network connections.

.DESCRIPTION
    Writes runtime\launch.conf with the system Python and a site-packages
    folder that the installer prepares with the app's dependencies. Then it
    reinstalls/restarts the Windows service so the change takes effect.

    The dependencies are installed into a private folder inside the bundle
    (runtime\system-site-packages), so the system Python installation itself
    is not modified. This step needs internet access the first time.

.PARAMETER PythonPath
    Full path to python.exe. Auto-detected when omitted.

.PARAMETER NoService
    Only write the config; do not reinstall or restart the service.

.PARAMETER NoElevate
    Do not request administrator rights automatically.
#>
[CmdletBinding()]
param(
    [string]$PythonPath,
    [switch]$NoService,
    [switch]$NoElevate
)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$runtimeDir = Join-Path $root 'runtime'
$confPath = Join-Path $runtimeDir 'launch.conf'
$siteDir = Join-Path $runtimeDir 'system-site-packages'
$requirements = Join-Path $root 'backend\requirements.txt'
$serviceName = 'PROCURE360'

function Write-Step { param([string]$m) Write-Host ''; Write-Host "==> $m" -ForegroundColor Cyan }
function Write-Ok { param([string]$m) Write-Host "  OK  $m" -ForegroundColor Green }
function Write-Warn { param([string]$m) Write-Host "  !!  $m" -ForegroundColor Yellow }

function Test-IsAdmin {
    $principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
    return $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

if (-not $NoElevate -and -not $NoService -and -not (Test-IsAdmin)) {
    $scriptPath = $PSCommandPath
    if ([string]::IsNullOrWhiteSpace($scriptPath)) { $scriptPath = $MyInvocation.MyCommand.Path }
    try {
        $process = Start-Process -FilePath 'powershell.exe' -Verb RunAs -Wait -PassThru -ArgumentList @(
            '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', "`"$scriptPath`""
        )
        exit $process.ExitCode
    } catch {
        Write-Host 'Administrator permission is required to restart the service.' -ForegroundColor Red
        exit 2
    }
}

function Get-SystemPython {
    param([string]$Provided)
    if (-not [string]::IsNullOrWhiteSpace($Provided)) {
        if (-not (Test-Path -LiteralPath $Provided)) { throw "Python not found at $Provided" }
        return $Provided
    }
    foreach ($cmd in @('py.exe', 'python.exe', 'python3.exe')) {
        $found = Get-Command $cmd -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($found) { return $found.Source }
    }
    throw 'No system Python found. Install Python 3.14 from python.org, or pass -PythonPath.'
}

Write-Host ''
Write-Host '  PROCURE360 - use system Python' -ForegroundColor White
Write-Host ''

Write-Step 'Locating system Python'
$python = Get-SystemPython -Provided $PythonPath
$version = & $python -c "import sys; print('%d.%d' % sys.version_info[:2])" 2>&1
Write-Ok "Using $python (Python $version)"

Write-Step 'Preparing private site-packages'
if (-not (Test-Path -LiteralPath $requirements)) {
    throw "requirements.txt is missing at $requirements"
}
New-Item -ItemType Directory -Path $siteDir -Force | Out-Null
& $python -m pip install --disable-pip-version-check --upgrade `
    --target $siteDir -r $requirements
if ($LASTEXITCODE -ne 0) {
    Write-Warn "pip install failed (exit $LASTEXITCODE). The switch was not applied."
    exit 1
}
Write-Ok "Dependencies installed in $siteDir"

Write-Step 'Writing launch configuration'
$content = @(
    "# PROCURE360 runtime override - generated by Use-SystemPython.ps1",
    "python=$python",
    "site-packages=$siteDir"
) -join "`r`n"
[IO.File]::WriteAllText($confPath, $content + "`r`n", (New-Object Text.UTF8Encoding($false)))
Write-Ok "Configuration written to $confPath"

if ($NoService) {
    Write-Warn 'Service not restarted (-NoService). Run Restart-Service PROCURE360 to apply.'
} else {
    Write-Step 'Restarting the PROCURE360 service'
    $service = Get-Service -Name $serviceName -ErrorAction SilentlyContinue
    if ($service) {
        Restart-Service -Name $serviceName -Force
        Start-Sleep -Seconds 3
        $service = Get-Service -Name $serviceName
        if ($service.Status -ne 'Running') { throw "Service is not running after restart (status: $($service.Status))." }
        Write-Ok 'Service restarted with the system Python'
    } else {
        Write-Warn 'The PROCURE360 service is not installed. Start the app manually to apply.'
    }
}

Write-Host ''
Write-Host 'Done. Try accessing PROCURE360 from another PC again.' -ForegroundColor Green
Write-Host "To revert to the bundled runtime, delete: $confPath" -ForegroundColor DarkGray
